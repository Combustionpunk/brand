/**
 * The forum's Discourse theme component, generated into `discourse/` by `pnpm build`.
 * See docs/discourse-install.md for installing it.
 */
import { sharedDeclarations, themeDeclarations } from "./css.ts";
import { toDiscourseScheme, type DiscourseColourName } from "./discourse.ts";
import type { ThemeKey, Tokens } from "./types.ts";

/**
 * The attribute on `<html>` that names the brand theme on the forum. Not `data-theme`, to keep
 * clear of Discourse's `data-theme-id` and of other components. The component's script sets it from the member's colour scheme.
 */
export const FORUM_THEME_ATTRIBUTE = "data-rm-theme";

/** The repo the component comes from. */
export const ABOUT_URL = "https://github.com/Combustionpunk/brand";

/**
 * For a colour scheme that is not exactly a brand theme (one an admin made or changed),
 * the `--rm-*` colours come from Discourse's own colour variables instead.
 */
export const DISCOURSE_FALLBACK: Record<ThemeKey, string> = {
  bg: "var(--secondary)",
  surface: "var(--header_background)",
  surface2: "var(--primary-very-low)",
  line: "var(--primary-low)",
  text: "var(--primary)",
  muted: "var(--primary-medium)",
  accent: "var(--tertiary)",
  onAccent: "var(--secondary)",
  good: "var(--success-low)",
  goodText: "var(--primary)",
  pb: "var(--success)",
  fast: "var(--quaternary)",
  danger: "var(--danger)",
  warning: "var(--highlight)",
};

/** Discourse's numbers that should line up: counts, dates, badges, and the brand's own class. */
export const TABULAR_SELECTORS = [
  ".rm-figures",
  ".topic-list .num",
  ".topic-list .posts",
  ".topic-list .views",
  ".topic-list .activity",
  ".relative-date",
  ".badge-notification",
  ".user-stat .value",
  ".number",
  ".cooked table td",
];

/** Theme ids in the order the forum lists them: the default, the default light, then the rest. */
export function discourseSchemeOrder(tokens: Tokens): string[] {
  const first = [tokens.defaultTheme, tokens.defaultLightTheme];
  return [...first, ...Object.keys(tokens.themes).filter((id) => !first.includes(id))];
}

export interface FontAsset {
  /** The SCSS variable Discourse gives the uploaded file: `$rm-oswald-latin`. */
  variable: string;
  /** The file name in fonts/ and discourse/assets/. */
  file: string;
}

const FONT_URL = /url\("\.\/([a-z0-9-]+)\.woff2"\)/g;

/** The woff2 files fonts.css uses, each with its Discourse asset variable. */
export function fontAssets(fontsCss: string): FontAsset[] {
  return [...fontsCss.matchAll(FONT_URL)].map(([, name]) => ({
    variable: `rm-${name!.replace(/-wght-normal$/, "")}`,
    file: `${name}.woff2`,
  }));
}

export interface AboutJson {
  name: string;
  component: true;
  about_url: string;
  license_url: string;
  authors: string;
  assets: Record<string, string>;
  color_schemes: Record<string, Record<DiscourseColourName, string>>;
}

/** The component's `about.json`. */
export function renderAboutJson(tokens: Tokens, fontsCss: string): AboutJson {
  return {
    name: "RC Misfits",
    component: true,
    about_url: ABOUT_URL,
    license_url: `${ABOUT_URL}/tree/main/fonts`,
    authors: "RC Misfits",
    assets: Object.fromEntries(fontAssets(fontsCss).map((asset) => [asset.variable, `assets/${asset.file}`])),
    color_schemes: Object.fromEntries(
      discourseSchemeOrder(tokens).map((id) => {
        const scheme = toDiscourseScheme(id, tokens.themes[id]!);
        return [scheme.name, scheme.colors];
      }),
    ),
  };
}

const rule = (selector: string, lines: string[]) => `${selector} {\n${lines.map((line) => `  ${line}`).join("\n")}\n}\n`;

/** The component's `common/common.scss`: fonts, tokens, the header's CSS and Discourse's fonts and figures. */
export function renderThemeScss(tokens: Tokens, fontsCss: string, headerCss: string): string {
  const fonts = fontsCss.replace(FONT_URL, (_, name: string) => {
    const asset = fontAssets(`url("./${name}.woff2")`)[0]!;
    return `url($${asset.variable})`;
  });
  const fallback = Object.entries(DISCOURSE_FALLBACK).map(([key, value]) => {
    const name = `--rm-${key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;
    return `${name}: ${value};`;
  });

  const parts = [
    "/* RC Misfits theme component. Generated by `pnpm build` in Combustionpunk/brand: do not edit here. */\n",
    fonts.trim() + "\n",
    "/* Shared tokens: type, spacing, radii and race colours. */\n" + rule(":root", sharedDeclarations(tokens)),
    `/* The brand theme Discourse is showing. The component's script sets ${FORUM_THEME_ATTRIBUTE} on <html>. */`,
    ...discourseSchemeOrder(tokens).map((id) =>
      `/* ${tokens.themes[id]!.name} */\n` + rule(`html[${FORUM_THEME_ATTRIBUTE}="${id}"]`, themeDeclarations(tokens.themes[id]!.colours)),
    ),
    "/* A colour scheme that is not a brand theme: Discourse's own colours. */\n" +
      rule(`html:not([${FORUM_THEME_ATTRIBUTE}])`, fallback),
    "/* Discourse's text in Inter, its headings in Oswald. */\n" +
      rule(":root", ["--font-family: var(--rm-font-body);", "--heading-font-family: var(--rm-font-display);"]),
    "/* Numbers line up: figures of equal width. */\n" +
      rule(TABULAR_SELECTORS.join(",\n"), ["font-variant-numeric: tabular-nums;", 'font-feature-settings: "tnum" 1;']),
    "/* The shared top bar carries the logo, so Discourse's own header does not repeat it. */\n" +
      rule(".d-header .title", ["display: none;"]),
    headerCss.trim() + "\n",
  ];
  return parts.join("\n");
}
